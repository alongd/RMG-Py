"""Freeze the before side of correction C-1 and the legacy certificate
snapshot (I-165 S2b).  Run ONCE on the S2a source (``34b7fd0fb``, byte-
identical to ``59246f18b`` for legacy witnesses); the files it writes are
never regenerated by a test.

``--part c1`` (R_Recombination): for ``c16`` (``("alkane", 16, None, None)``)
R_Recombination reverse, every member's first-observation certificate
(``MemberObserver``, the path that sets the depository growth unit): per
channel its ``depository_exclusion`` verdict and growth unit, and the
certificate's ``eligible``/``complete`` -> ``data/c1_before.json``.

``--part snapshot`` (H_Abstraction): the certificate of the first supported
member of legacy PS DP3 + H forward, certified with no domain ->
``data/legacy_ps_dp3_h_certificate.json``.

One kinetics family per process (``one_family.family_db``)."""

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
DATA = HERE / "data"

C16 = [("alkane", 16, None, None)]


def c1_rows(certifier, family, cases, observer_kwargs=None) -> dict:
    """member label -> its first-observation certificate's C-1 facts."""
    from rmgpy.kmc import windows as win
    out = {}
    for case in cases:
        if case.support != "supported":
            continue
        observer = win.MemberObserver(certifier, family, case.direction, case.wanted,
                                      **(observer_kwargs or {}))
        cert = observer(case.witness).certificate
        out[case.label] = {
            "eligible": bool(cert.get("eligible")), "complete": bool(cert.get("complete")),
            "channels": [{"pathway": ";".join(ch.get("pathway", [])),
                          "verdict": (ch.get("depository_exclusion") or {}).get("verdict"),
                          "repeat_unit": (ch.get("depository_exclusion") or {}).get(
                              "repeat_unit")}
                         for ch in cert.get("channels", [])]}
    return out


def capture_c1():
    import one_family
    from rmgpy.kmc import certificates as cm
    from rmgpy.kmc import windows as win
    db = one_family.family_db("R_Recombination")
    fams = db.kinetics.families
    family = fams["R_Recombination"]
    certifier = cm.Certifier(fams, max_channel_sets=16)
    cases = win.member_cases(certifier, family, win.builds_of(C16), "reverse", label="c16")
    rows = c1_rows(certifier, family, cases)
    payload = {"reference": "c16", "family": "R_Recombination", "direction": "reverse",
               "source": "S2a tip 34b7fd0fb (legacy witnesses byte-identical to 59246f18b)",
               "members": rows}
    (DATA / "c1_before.json").write_text(json.dumps(payload, sort_keys=True, indent=1) + "\n")
    print(f"c1_before.json: {len(rows)} members")


def ps_dp3_h_certificate(certifier, family, **certify_kwargs) -> dict:
    """The legacy PS DP3 + H certificate of the snapshot (first supported
    member, certified on its template molecules)."""
    from rmgpy.kmc import boundaries as b
    from rmgpy.kmc import windows as win
    specs = [b.PsChainSpec(3), ("small", "H")]
    cases = win.member_cases(certifier, family, win.builds_of(specs), "forward", label="PS3+H")
    case = next(c for c in cases if c.support == "supported")
    cert = certifier.certify(family, win.template_molecules(case.witness, "forward"),
                             member_labels=case.wanted, **certify_kwargs)
    return {"member": case.label, "certificate": cert}


def canonical(value) -> str:
    return json.dumps(value, sort_keys=True, default=str, indent=None, separators=(",", ":"))


def capture_snapshot():
    import one_family
    from rmgpy.kmc import certificates as cm
    db = one_family.family_db("H_Abstraction")
    fams = db.kinetics.families
    certifier = cm.Certifier(fams, max_channel_sets=16)
    out = ps_dp3_h_certificate(certifier, fams["H_Abstraction"])
    (DATA / "legacy_ps_dp3_h_certificate.json").write_text(
        json.dumps(json.loads(canonical(out)), sort_keys=True, indent=1) + "\n")
    print(f"legacy_ps_dp3_h_certificate.json: {out['member']}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--part", choices=("c1", "snapshot"), required=True)
    args = parser.parse_args()
    DATA.mkdir(exist_ok=True)
    capture_c1() if args.part == "c1" else capture_snapshot()
