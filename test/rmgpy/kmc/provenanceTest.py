def test_fixed_flag_terms_cover_reference_and_clean_controls():
    assert FLAG_TERMS == (
        "Kruse",
        "Broadbelt",
        "Levine",
        "polystyrene",
        "polyethylene",
        "polypropylene",
        "polymer",
        "pyrolysis",
        "TGA",
        "thermogravimetr",
        "oligomer",
        "plastic",
        "Poutsma",
    )

    flagged = Entry(
        index=1,
        label="flagged",
        reference=Reference(authors=["T. M. Kruse"], title="A rate"),
    )
    clean = Entry(
        index=2,
        label="clean",
        short_desc="Gas-phase radical kinetics",
        reference=Reference(authors=["A. N. Other"], title="A clean rate"),
    )

    assert entry_flag_terms(flagged) == ["Kruse"]
    assert entry_flag_terms(clean) == []


