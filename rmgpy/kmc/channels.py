"""Kinetic channels of RMG records: whole-channel normalization, filtered
moves, spin scope, and rate-selection certificates.

A **channel** is (family, direction, pathway = RMG template labels, reactant
species, product species).  On one set of reactant molecules (a witness or a
reference) its **members** are the distinct mapped outcomes
(``rmg_moves.product_key``) of the directed ``rmg_moves`` moves whose template
labels and product SPECIES (RMG isomorphism, not mapped identity) match.  A
compiled RMG record of that channel carries ``k_record``, which already holds
RMG's reaction-path degeneracy summed over all of those outcomes, so the
per-transition weight is

    w = ssa_multiplier * k_record / T_ch,    T_ch = number of members,

and ``sum(w over members) = ssa_multiplier * k_record`` exactly (the whole
channel is the denominator, never the outcomes equal to one fixed product).

Collapse of raw mappings into members (raw mapping counts are diagnostics only)
---------------------------------------------------------------------------------
* resonance-form duplicates: one transfer found from two forms of a reactant
  is one mapped outcome modulo resonance (``product_key``), so one member;
* homolysis: RMG maps each bond in both ``*`` orientations; both orientations
  make the same mapped product, so one member per bond;
* A + A and A + B: RMG tries both template slot orders; a symmetric family
  (R_Recombination) gives the same mapped product twice, one member; an
  ordered family (Disproportionation) gives (acceptor A, donor B) and
  (acceptor B, donor A) as different mapped products, two members.

The SSA pair convention is the compiler's: an ordered unimolecular channel and
a distinct A + B pair count ``N`` and ``N_A*N_B`` (multiplier 1); an
identical-species pair counts ``N(N-1)/2`` and carries multiplier 2, because
RMG's degeneracy for A + A already holds the factor 1/2.

Filtered moves
--------------
* Mappings are quotiented first: an outcome with at least one allowed mapping
  (``kept`` or ``unchanged_species``) is allowed even if another mapping of
  the same outcome is ``forbidden``.
* ``unchanged_species`` outcomes (products are the reactant species, e.g. a
  chain-to-chain H transfer that swaps the roles of two equal species) form a
  synthetic channel; ``channel_kinetics`` rates it by RMG's own family
  kinetics for its template (``KineticsFamily.get_kinetics``, the call the
  compiler makes for a kept reaction) with provenance
  ``synthetic:unchanged_species``.  A channel
  whose product species are its reactant species and whose mappings RMG
  files as ``unchanged_species`` on some resonance forms and ``kept`` on
  others (its identity test is strict on the forms) is one synthetic
  channel; any other mix of the two statuses raises ``ChannelError``.
* Outcomes whose every mapping is ``forbidden`` are excluded with the fired
  rule names and their disposition (``FORBIDDEN_DISPOSITIONS``).

Spin scope (separated-radical policy, ``domain.spin_verdict``; a declared
approximation, not physics): ``MeltState`` carries no multiplicity.  A species
with two or more unpaired electrons is supported when no atom is ``u2`` and
every pair of radical sites is more than ``domain.RADICAL_SEPARATION`` heavy
bonds apart and not in one pi system; the bridge builds it with the maximum
multiplicity (``domain.MULTIPLICITY_CONVENTION``).  A channel with any other
multi-radical species is ``unsupported:spin``.  The verdict is per species,
so two doublets on different participants are never refused for that reason.

Pathway ambiguity: an outcome that is a member of channels of two or more
pathways (RMG reads a different tree leaf from another resonance form of a
remote radical centre of the same reactant) marks each of those channels
``pathway_ambiguous`` (unless ``unsupported:spin``), with ``ambiguous_with``
naming the other pathways; it is reported, never silently supported.

``selection_certificate`` records how RMG chooses the rate of a channel: the
source kind, the matched leaf per reactant group, the node supplying the
kinetics, averaged contributors, and the full tree descent with every child
predicate tried (matched / failed) mapped onto the witness atom ids.
"""

import math
import re
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from typing import Callable, Dict, Optional, Sequence, Tuple

from rmgpy.kmc import rmg_moves as rm

ALLOWED_STATUSES = ("kept", "unchanged_species")
KINDS = ("kept", "synthetic:unchanged_species")
SOURCE_KINDS = ("rate_rule", "rate_rule_from_training", "averaged", "training_exact_match",
                "autogenerated_tree", "library", "unsupported")
SPIN_UNSUPPORTED = "unsupported:spin"
PATHWAY_AMBIGUOUS = "pathway_ambiguous"
SUPPORTED = "supported"


class ChannelError(ValueError):
    """Bad input, or a channel invariant failed."""


# ---------------------------------------------------------------------------
# forbidden-rule dispositions (see ``forbidden_disposition_table``)
# ---------------------------------------------------------------------------
@dataclass(frozen=True)
class Disposition:
    family: str
    rule: str
    disposition: str          # "exclude" | "include"
    covered_by: Optional[str]  # family covering the same physical outcome, if any
    reason: str


_DISPROPORTIONATION = ("the H leaves an atom bonded to a radical centre (directly, or through "
                       "a conjugated path in the resonance form the rule fires on), so the "
                       "product pairs into a closed shell: the outcome of Disproportionation, "
                       "which rates it; counting it here too would count it twice")
FORBIDDEN_DISPOSITIONS = {
    ("H_Abstraction", rule): Disposition("H_Abstraction", rule, "exclude", "Disproportionation",
                                         _DISPROPORTIONATION)
    for rule in ("disprop1_base_case", "disprop2", "disprop4", "disprop5")
}


def disposition(family: str, rule: str) -> Optional[Disposition]:
    return FORBIDDEN_DISPOSITIONS.get((family, rule))


_FORBIDDEN_RE = re.compile(r"forbidden (reactant|product) \(([^)]*)\)")


def fired_rules(move) -> Tuple[Tuple[str, str], ...]:
    """(where, rule name) of a forbidden move, from its status reason."""
    hit = _FORBIDDEN_RE.search(move.reason)
    if hit is None:
        raise ChannelError(f"not a forbidden move: {move.status} ({move.reason})")
    names = [n.strip() for n in hit.group(2).split(",") if n.strip()]
    return tuple((hit.group(1), n) for n in names)


# ---------------------------------------------------------------------------
# species identity (per call; never global)
# ---------------------------------------------------------------------------
def _radical_count(mol) -> int:
    return sum(int(a.radical_electrons) for a in mol.atoms)


_SPIN_CACHE = {}
_SPIN_CACHE_MAX = 4096


def spin_supported(mol) -> bool:
    """``domain.spin_verdict`` of one species (bounded cache by signature)."""
    if _radical_count(mol) <= 1 and not any(a.radical_electrons >= 2 for a in mol.atoms):
        return True
    from rmgpy.kmc import domain
    sig = rm._signature(rm.molecule_rows(mol))
    if sig not in _SPIN_CACHE:
        if len(_SPIN_CACHE) >= _SPIN_CACHE_MAX:
            _SPIN_CACHE.pop(next(iter(_SPIN_CACHE)))
        _SPIN_CACHE[sig] = domain.spin_verdict(mol).supported
    return _SPIN_CACHE[sig]


class SpeciesKeys:
    """Species identity of molecules: RMG isomorphism modulo resonance.

    The key is the least canonical SMILES among the most aromatic (most
    1.5-order bonds) of the reactive forms
    ``generate_resonance_structures(keep_isomorphic=False)`` returns.  The
    form set depends on the starting form (a Kekule ring in the input comes
    back as an extra form, sometimes marked reactive), but RMG's aromatic
    forms are generated from every start, so the most aromatic forms are the
    same and isomorphic molecules share a key.  Every
    key's first molecule is kept and later molecules with the same key are
    checked isomorphic to it (``Molecule.is_isomorphic`` over its forms), so
    a key collision of two different species raises.  Scoped to one owner (a
    ``ChannelSet`` build), never global."""

    def __init__(self):
        self._by_sig = {}
        self._first = {}

    @staticmethod
    def _forms(mol):
        from rmgpy.molecule.resonance import generate_resonance_structures
        base = mol.copy(deep=True)
        if len(base.atoms) == 1:
            return [base]
        forms = generate_resonance_structures(base, keep_isomorphic=False, filter_structures=True)
        return [f for f in forms if f.reactive] or list(forms)

    def __call__(self, mol) -> str:
        # keyed on a numbered copy: the caller's ids may be absent (-1 on
        # every atom) or anything; the key never depends on them
        mol = mol.copy(deep=True)
        for k, atom in enumerate(mol.atoms):
            atom.id = k
        sig = rm._signature(rm.molecule_rows(mol))
        if sig in self._by_sig:
            return self._by_sig[sig]
        forms = self._forms(mol)
        key = min((-sum(1 for b in f.get_all_edges() if b.is_benzene()), f.to_smiles())
                  for f in forms)[1]
        first = self._first.get(key)
        if first is None:
            self._first[key] = forms
        elif not any(f.is_isomorphic(g) for f in forms for g in first):
            raise ChannelError(f"two non-isomorphic species share the key {key!r}")
        self._by_sig[sig] = key
        return key


