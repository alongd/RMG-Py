def connectivity_key(rows: Dict[int, Tuple]) -> Tuple:
    """The mapped sigma skeleton of a product: bonded atom-id pairs, bond
    orders and electrons ignored.  Two outcomes with equal keys differ only by
    electron placement (e.g. a singlet 1,2-biradical and the alkene)."""
    return tuple(sorted((a, b) for a, row in rows.items() for b, _o in row[5] if a < b))


def _resonance_atoms(mol, resonance="all"):
    """Atoms whose row differs across the reactive forms of ``mol`` (its
    conjugated, resonance-active part)."""
    forms = rm.reactant_forms(mol, resonance)
    rows = [rm.molecule_rows(f) for f in forms]
    return sorted(a for a in rows[0] if len({r[a] for r in rows}) > 1)


def _distances(mol, sources):
    by_id = {a.id: a for a in mol.atoms}
    dist = {s: 0 for s in sources}
    frontier = [by_id[s] for s in sources]
    while frontier:
        nxt = []
        for a in frontier:
            for b in a.bonds:
                if b.id not in dist:
                    dist[b.id] = dist[a.id] + 1
                    nxt.append(b)
        frontier = nxt
    return dist


def forbidden_rule_rows(family, channel_set: ChannelSet,
                        covering: Optional[Dict[str, ChannelSet]] = None) -> Tuple[dict, ...]:
    """One row per forbidden rule that fires on ``channel_set``'s moves.

    ``radius``: the largest bond distance, on the witness, from the move's
    reacting (labelled) atoms to any atom the rule's group maps onto, over every
    firing mapping (the rule reads nothing farther, on the resonance form it is
    evaluated on); ``resonance_radius``: the largest distance from the reacting
    atoms to an atom of the reactant's resonance-active part when the firing
    form is not the first one (the form itself is decided there);
    ``outcomes``: firing outcomes, split into excluded (no allowed mapping) and
    allowed-by-quotient; ``covered_by``: families of ``covering`` whose kept
    outcomes on the same reactants have the excluded outcome's connectivity."""
    from rmgpy.molecule.group import Group
    keys = rm.product_key
    allowed = {o for ch in channel_set.channels for o in ch.members}
    covered = {}
    for name, other in (covering or {}).items():
        covered[name] = {connectivity_key(dict(ch_rep.products)) for ch in other.channels
                         for ch_rep in ch.representatives}
    rows = {}
    for move in channel_set.moves:
        if move.status != "forbidden":
            continue
        outcome = keys(move) if move.products is not None else None
        reacts = _labelled_reactant_forms(channel_set, move)
        label_ids = {a for _s, _l, a in move.labels}
        for where, rule in fired_rules(move):
            entry = family.forbidden.entries[rule]
            row = rows.setdefault(rule, {
                "family": family.label, "rule": rule, "where": set(), "moves": 0,
                "forms": set(), "radius": 0, "resonance_radius": 0, "excluded_outcomes": set(),
                "allowed_by_quotient": set(), "covered_by": None, "uncovered": 0})
            row["where"].add(where)
            row["moves"] += 1
            row["forms"].add(move.forms)
            group = entry.item
            if where == "reactant" and isinstance(group, Group):
                for mol in reacts:
                    labels = mol.get_all_labeled_atoms()
                    if not all(lab in labels for lab in group.get_all_labeled_atoms()):
                        continue
                    if not mol.is_subgraph_isomorphic(group, generate_initial_map=True):
                        continue
                    initial = {labels[lab]: g for lab, g in group.get_all_labeled_atoms().items()
                               if not isinstance(g, list) and not isinstance(labels[lab], list)}
                    dist = _distances(mol, sorted(label_ids & {a.id for a in mol.atoms}))
                    for mapping in mol.find_subgraph_isomorphisms(group, initial_map=initial):
                        row["radius"] = max(row["radius"],
                                            max(dist[a.id] for a in mapping))
                    k = channel_set.reactants.index(next(
                        m for m in channel_set.reactants
                        if {a.id for a in m.atoms} == {a.id for a in mol.atoms}))
                    if move.forms[k] != 0:
                        active = _resonance_atoms(channel_set.reactants[k], channel_set.resonance)
                        row["resonance_radius"] = max([row["resonance_radius"]] +
                                                      [dist[a] for a in active])
            else:
                row["radius"] = None  # product-side or logic rule: not measured
            if outcome is None:
                continue
            if outcome in allowed:
                row["allowed_by_quotient"].add(outcome)
            else:
                row["excluded_outcomes"].add(outcome)
                skel = connectivity_key(dict(move.products))
                hits = sorted(n for n, keys_ in covered.items() if skel in keys_)
                if hits:
                    row["covered_by"] = ",".join(hits)
                else:
                    row["uncovered"] += 1
    out = []
    for rule in sorted(rows):
        row = rows[rule]
        disp = disposition(family.label, rule)
        out.append({
            "family": row["family"], "rule": rule, "where": sorted(row["where"]),
            "moves": row["moves"], "forms": sorted(row["forms"]),
            "radius": row["radius"], "resonance_radius": row["resonance_radius"],
            "decidable_locally": row["radius"] is not None,
            "excluded_outcomes": len(row["excluded_outcomes"]),
            "allowed_by_quotient": len(row["allowed_by_quotient"]),
            "covered_by": row["covered_by"] if not row["uncovered"] else None,
            "uncovered_excluded": row["uncovered"],
            "disposition": disp.disposition if disp else "undecided",
        })
    return tuple(out)


def spin_unsupported(channel_sets) -> Tuple[Tuple, ...]:
    """(family, direction, pathway, reactants, products) of every channel marked
    ``unsupported:spin``."""
    return tuple(sorted(ch.key for cs in channel_sets for ch in cs.channels
                        if ch.support == SPIN_UNSUPPORTED))


