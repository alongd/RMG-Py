CERTIFICATE_VERSION = "kmc-rate-selection-certificate/1"


class UnsupportedSelection(ChannelError):
    """RMG selected the rate by semantics the certificate cannot state."""


def _group_atoms(database, node):
    """The concrete Groups behind a tree node (a LogicNode expands to its
    possible structures)."""
    from rmgpy.data.base import LogicNode
    item = node.item
    if isinstance(item, LogicNode):
        try:
            return list(item.get_possible_structures(database.entries))
        except NotImplementedError as exc:
            raise UnsupportedSelection(f"logic node {node.label}: {exc}") from None
    return [item]


def _group_radius(group):
    """Largest bond distance from the group's labelled atoms to any of its atoms
    (None if a group atom is not connected to a labelled atom)."""
    labelled = [a for a in group.atoms if a.label]
    if not labelled:
        return None
    dist = {id(a): 0 for a in labelled}
    frontier = list(labelled)
    while frontier:
        nxt = []
        for a in frontier:
            for b in a.bonds:
                if id(b) not in dist:
                    dist[id(b)] = dist[id(a)] + 1
                    nxt.append(b)
        frontier = nxt
    if len(dist) != len(group.atoms):
        return None
    return max(dist.values())


def _ball(structure, centres, radius):
    dist = {a: 0 for a in centres}
    frontier = list(centres)
    for _ in range(radius):
        nxt = []
        for a in frontier:
            for b in a.bonds:
                if b not in dist:
                    dist[b] = dist[a] + 1
                    nxt.append(b)
        frontier = nxt
    return dist


def _scope_rows(atoms):
    """Integer-keyed rows of witness atoms (the structure a predicate can see)."""
    ids = {a.id for a in atoms}
    rows = []
    for a in sorted(atoms, key=lambda x: x.id):
        rows.append([a.id, a.element.symbol, int(a.radical_electrons), int(a.charge),
                     int(a.lone_pairs), sorted([b.id, float(bond.order)]
                                               for b, bond in a.bonds.items() if b.id in ids)])
    return rows


def _labelled_ids(atoms):
    out = {}
    for label, atom in sorted(atoms.items()):
        out[label] = sorted(a.id for a in atom) if isinstance(atom, list) else atom.id
    return out


def _predicate(database, node, structure, atoms, result):
    """One tree predicate on the witness: the verdict (RMG's), the witness atoms
    the labelled group atoms map to, and the witness structure within the
    group's radius of them (what the verdict can depend on); a matched group
    also carries its least subgraph mapping (group atom index -> atom id)."""
    groups = _group_atoms(database, node)
    centres = []
    for label, atom in atoms.items():
        if any(label in g.get_all_labeled_atoms() for g in groups):
            centres.extend(atom if isinstance(atom, list) else [atom])
    radii = [_group_radius(g) for g in groups]
    if any(r is None for r in radii):
        raise UnsupportedSelection(f"node {node.label} has atoms not connected to a label")
    radius = max(radii)
    scope = _ball(structure, centres, radius)
    out = {"node": node.label, "result": "matched" if result else "failed",
           "logic": type(node.item).__name__ if not hasattr(node.item, "atoms") else None,
           "labelled_atoms": sorted({a.id for a in centres}), "radius": radius,
           "scope": _scope_rows(list(scope))}
    if result and hasattr(node.item, "atoms"):
        group = node.item
        initial = {}
        for label, gatom in group.get_all_labeled_atoms().items():
            satom = atoms.get(label)
            if isinstance(satom, list) or isinstance(gatom, list):
                initial = {}
                break
            if satom is not None:
                initial[satom] = gatom
        maps = structure.find_subgraph_isomorphisms(group, initial_map=initial or None)
        index = {g: k for k, g in enumerate(group.atoms)}
        keyed = sorted(sorted([index[g], s.id] for s, g in m.items()) for m in maps)
        out["mapping"] = keyed[0] if keyed else None
        out["mapping_count"] = len(keyed)
    return out


def _descend(database, structure, atoms, root):
    """``Database.descend_tree`` (rmgpy/data/base.py) with every child
    predicate recorded.  Returns (leaf entry, steps)."""
    steps = []
    node = root
    while True:
        children = []
        hits = []
        for child in node.children:
            ok = database.match_node_to_structure(child, structure, atoms, strict=True)
            children.append(_predicate(database, child, structure, atoms, ok))
            if ok:
                hits.append(child)
        step = {"node": node.label, "children": children}
        steps.append(step)
        if len(hits) == 1:
            step["choice"], step["rule"] = hits[0].label, "single match"
            node = hits[0]
        elif len(hits) > 1:
            step["choice"], step["rule"] = hits[0].label, f"first of {len(hits)} overlapping matches"
            node = hits[0]
        elif node.children and node.children[-1].label.startswith("Others-"):
            step["choice"], step["rule"] = node.children[-1].label, "no match: Others- fallback"
            return node.children[-1], steps
        else:
            step["choice"], step["rule"] = None, "no child matched: stop"
            return node, steps


def _template_descent(family, reactant_molecules):
    """Every top-level descent of ``groups.get_reaction_template`` (the same
    branches), recorded."""
    from rmgpy.data.base import LogicNode
    database = family.groups
    tops = []
    for entry in database.top:
        if entry not in tops:
            tops.append(entry)
    out = []
    if len(tops) == 1 and len(reactant_molecules) > 1:
        merged = reactant_molecules[0]
        for other in reactant_molecules[1:]:
            merged = merged.merge(other)
        atoms = merged.get_all_labeled_atoms()
        root = tops[0]
        if not database.match_node_to_structure(root, merged, atoms, strict=True):
            raise UnsupportedSelection(f"top node {root.label} does not match the merged reactants")
        leaf, steps = _descend(database, merged, atoms, root)
        out.append({"top": root.label, "structure": "merged reactants",
                    "labelled": _labelled_ids(atoms), "steps": steps, "leaf": leaf.label})
        return out
    for entry in tops:
        labels = [] if isinstance(entry.item, LogicNode) else list(entry.item.get_all_labeled_atoms())
        for k, mol in enumerate(reactant_molecules):
            if not all(mol.contains_labeled_atom(lab) for lab in labels):
                continue
            atoms = mol.get_all_labeled_atoms()
            if not database.match_node_to_structure(entry, mol, atoms, strict=True):
                continue
            leaf, steps = _descend(database, mol, atoms, entry)
            out.append({"top": entry.label, "structure": f"template reactant {k}",
                        "labelled": _labelled_ids(atoms), "steps": steps, "leaf": leaf.label})
    return out


def _rule_entry_data(entry):
    if entry is None:
        return None
    desc = entry.short_desc or ""
    origin = ("training-derived rule" if desc.startswith("Rate rule generated from training")
              else "averaged rule" if "Average of" in (getattr(entry.data, "comment", "") or "")
              else "database rule")
    return {"label": entry.label, "index": entry.index, "rank": entry.rank, "origin": origin}


_TEMPLATE_RE = re.compile(r"Estimated using template \[([^\]]*)\]")
_AVERAGE_RE = re.compile(r"Estimated using average of templates (.*) for rate rule")


def _rate_rule_selection(family, template_labels, kinetics):
    """Which rule nodes supplied a rate-rule estimate (hand-built trees),
    read from RMG's own estimate (``KineticsRules.estimate_kinetics``)."""
    rules = family.rules
    comment = kinetics.comment or ""
    leaves = ";".join(template_labels)
    if "Exact match found" in comment or "Estimated using an average" in comment:
        supplying = [leaves]
    else:
        single = _TEMPLATE_RE.search(comment)
        average = _AVERAGE_RE.search(comment.replace("\n", " "))
        if single is not None and average is None:
            supplying = [single.group(1)]
        elif average is not None:
            supplying = [t.strip()[1:-1] for t in average.group(1).split(" + ")]
        else:
            raise UnsupportedSelection(f"rate-rule comment not understood: {comment!r}")
    contributors = []
    for label in supplying:
        template = family.retrieve_template(label.split(";"))
        entry = rules.get_rule(template)
        if entry is None:
            raise UnsupportedSelection(f"supplying template [{label}] has no rule")
        contributors.append({"template": label.split(";"), "rule": _rule_entry_data(entry)})
    averaged = len(supplying) > 1 or any(c["rule"]["origin"] == "averaged rule"
                                         for c in contributors)
    kind = "averaged" if averaged else (
        "rate_rule_from_training" if contributors[0]["rule"]["origin"] == "training-derived rule"
        else "rate_rule")
    exact = supplying == [leaves]
    # an averaged rule is not one contributor: its underlying rules and
    # training entries with their weights, extracted exactly as production
    # serializes them (compiler._rate_rule_source over RMG's comment)
    return kind, {"exact_template": exact, "supplying_templates": [c["template"] for c in contributors],
                  "contributors": contributors,
                  "sources": production_sources(family, template_labels, kinetics)}


def production_sources(family, template_labels, kinetics) -> dict:
    """``compiler._rate_rule_source`` (RMG's ``extract_source_from_comments``
    and ``get_sources_for_template``) on a tree estimate: the exact flag and
    every rule and training entry with its weight."""
    from types import SimpleNamespace
    from rmgpy.kmc.compiler import _rate_rule_source
    source = _rate_rule_source(family, SimpleNamespace(kinetics=kinetics,
                                                       template=list(template_labels)))
    return {"exact": source.get("exact"), "rules": source.get("rules"),
            "training": source.get("training")}


def autogenerated_walk(family, template_labels):
    """The uncertainty walk of ``KineticsRules.estimate_kinetics`` for an
    auto-generated tree (rmgpy/data/kinetics/rules.py), evaluated WITHOUT
    calling RMG: from the leaf rule, move to the parent while the entry's
    error exceeds the parent's; stop at the first step that does not move, or
    at the root.  Every step is recorded.

    RMG's own loop never stops on a step that does not move (it has no
    ``else: break``) and spins forever once a parent link exists there, so a
    walk with such a step is reported ``rmg_terminates=False`` and the caller
    must not call RMG on it.  Raises ``UnsupportedSelection`` without a leaf
    rule or an uncertainty."""
    from math import pi, sqrt
    template = family.retrieve_template(list(template_labels))
    entry = family.rules.get_rule(template)
    if entry is None or entry.data is None:
        raise UnsupportedSelection(f"auto-generated leaf {template_labels} has no rule data")
    walk = []
    start = entry
    seen = {id(entry)}
    terminates = True
    while entry.parent is not None:
        parent = entry.parent
        try:
            u_parent, u_entry = parent.data.uncertainty, entry.data.uncertainty
            err_parent = abs(u_parent.data_mean + u_parent.mu - u_entry.data_mean) + \
                sqrt(2.0 * u_parent.var / pi)
            err_entry = abs(u_entry.mu) + sqrt(2.0 * u_entry.var / pi)
        except AttributeError as exc:
            raise UnsupportedSelection(f"node {entry.label} has no uncertainty: {exc}") from None
        moved = err_entry > err_parent
        walk.append({"from": entry.label, "parent": parent.label, "err_entry": err_entry,
                     "err_parent": err_parent, "moved": moved})
        if not moved:
            terminates = False
            break
        if id(parent) in seen:
            raise UnsupportedSelection(f"parent links of {start.label} form a cycle")
        seen.add(id(parent))
        entry = parent
    return {"matched": start, "supplying": entry, "walk": walk, "rmg_terminates": terminates}


def _autogenerated_selection(family, template_labels, kinetics, walk=None):
    """``KineticsRules.estimate_kinetics`` for an auto-generated tree: the leaf
    rule, then the walk to parents (``autogenerated_walk``), checked against
    RMG's comment."""
    result = walk or autogenerated_walk(family, template_labels)
    if not result["rmg_terminates"]:
        raise UnsupportedSelection(
            f"RMG's estimate_kinetics walk does not terminate at {result['supplying'].label} "
            "(a step that does not move, with a parent link)")
    start, entry, walk = result["matched"], result["supplying"], result["walk"]
    comment = (kinetics.comment if kinetics is not None else "") or ""
    if f"Estimated from node {entry.label}" not in comment:
        raise UnsupportedSelection(f"walk ends at {entry.label}, RMG says {comment!r}")
    return {"matched_node": start.label, "supplying_node": entry.label,
            "returned_entry_is_none": entry is not start, "parent_walk": walk,
            "contributors": [{"template": [entry.label], "rule": _rule_entry_data(entry)}]}


def selection_certificate(family, channel_set: ChannelSet, channel: Channel) -> dict:
    """How RMG selects the rate of ``channel`` (see the module docstring).

    Never partial: any selection the certificate cannot state returns
    ``{"source_kind": "unsupported", "reason": ...}``."""
    head = {"version": CERTIFICATE_VERSION, "family": channel.family,
            "direction": channel.direction, "pathway": list(channel.pathway),
            "channel_kind": channel.kind, "reactants": list(channel.reactants),
            "products": list(channel.products)}
    try:
        body = _certificate_body(family, channel_set, channel)
    except UnsupportedSelection as exc:
        return {**head, "source_kind": "unsupported", "reason": str(exc)}
    return {**head, **body}


def _certificate_body(family, channel_set, channel):
    from rmgpy.data.base import Database
    move = channel.representatives[0]
    rxn, reacts, _prods = template_reaction(family, channel_set, move)
    if family.groups is None or not isinstance(family.groups, Database):
        raise UnsupportedSelection("family has no group tree")
    descent = _template_descent(family, _labelled_copies(reacts))
    leaves = [d["leaf"] for d in descent]
    if leaves != list(channel.pathway):
        raise UnsupportedSelection(f"recorded descent ends at {leaves}, the move's template is "
                                   f"{list(channel.pathway)}")
    rmg_leaves = family.get_reaction_template_labels(_reaction_for_template(rxn))
    if list(rmg_leaves) != leaves:
        raise UnsupportedSelection(f"RMG's get_reaction_template gives {rmg_leaves}")
    walk = None
    if family.auto_generated:
        # evaluated first: RMG's own walk may not terminate (see autogenerated_walk)
        walk = autogenerated_walk(family, channel.pathway)
        if not walk["rmg_terminates"]:
            _autogenerated_selection(family, channel.pathway, None, walk=walk)
    kinetics, source, entry, is_forward = family.get_kinetics(
        rxn, template_labels=list(channel.pathway), degeneracy=1, return_all_kinetics=False)
    body = {"matched_leaves": [{"top": d["top"], "leaf": d["leaf"]} for d in descent],
            "descent": descent}
    source_label = getattr(source, "label", source)
    if not isinstance(source, str):
        # a depository (training reactions): RMG's whole-species isomorphism
        body["source_kind"] = "training_exact_match"
        body["training_entry"] = {"index": entry.index, "label": entry.label,
                                  "depository": str(source_label),
                                  "is_forward": bool(is_forward),
                                  "identified_by": "Reaction.is_isomorphic of the whole "
                                                   "reactant and product species"}
        body["supplying_node"] = None
        body["contributors"] = []
        return body
    if family.auto_generated:
        sel = _autogenerated_selection(family, channel.pathway, kinetics, walk=walk)
        body["source_kind"] = "autogenerated_tree"
        body.update(sel)
        return body
    kind, sel = _rate_rule_selection(family, channel.pathway, kinetics)
    body["source_kind"] = kind
    body["supplying_node"] = sel["supplying_templates"][0] if len(sel["supplying_templates"]) == 1 \
        else None
    body.update(sel)
    return body


def _labelled_copies(molecules):
    out = []
    for mol in molecules:
        copy = mol.copy(deep=True)
        for atom, original in zip(copy.atoms, mol.atoms):
            atom.id = original.id
            atom.label = original.label
        out.append(copy)
    return out


def _reaction_for_template(rxn):
    """A shallow reaction whose reactants are labelled Molecules (what
    ``get_reaction_template`` reads)."""
    from rmgpy.reaction import Reaction
    return Reaction(reactants=_labelled_copies([s.molecule[0] for s in rxn.reactants]),
                    products=[])


def certificate_json(certificate: dict) -> str:
    import json
    return json.dumps(certificate, sort_keys=True, separators=(",", ":"))
