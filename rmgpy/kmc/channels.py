@dataclass(frozen=True)
class Channel:
    """One kinetic channel on one reactant set.

    ``members``: distinct mapped outcomes (``product_key``), sorted;
    ``mappings``: raw RMG mappings per member (diagnostic only);
    ``quotiented_forbidden``: forbidden mappings per member dropped because the
    outcome also has an allowed mapping (diagnostic);
    ``representatives``: the first allowed move (sort order) per member."""

    family: str
    direction: str
    pathway: Tuple[str, ...]
    reactants: Tuple[str, ...]
    products: Tuple[str, ...]
    kind: str
    identical_reactants: bool
    members: Tuple[Tuple, ...]
    mappings: Tuple[int, ...]
    quotiented_forbidden: Tuple[int, ...]
    representatives: Tuple = field(repr=False, compare=False)
    support: str = "supported"
    ambiguous_with: Tuple[Tuple[str, ...], ...] = ()

    @property
    def key(self):
        return (self.family, self.direction, self.pathway, self.reactants, self.products)

    @property
    def size(self) -> int:
        """``T_ch``: the number of distinct mapped outcomes of the channel."""
        return len(self.members)

    @property
    def ssa_multiplier(self) -> float:
        """2 for an identical-species pair (SSA counts N(N-1)/2), else 1."""
        return 2.0 if self.identical_reactants else 1.0

    @property
    def pair_convention(self) -> str:
        if len(self.reactants) == 1:
            return "ordered-unimolecular"
        return ("unordered-identical-pair N(N-1)/2" if self.identical_reactants
                else "distinct-pair N_A*N_B")

    @property
    def degeneracy_convention(self) -> float:
        """RMG's path degeneracy for this channel by its own convention: the
        member count, times 1/2 for an identical-species pair."""
        return self.size * (0.5 if self.identical_reactants else 1.0)


@dataclass(frozen=True)
class ExcludedOutcome:
    """An outcome with no allowed mapping (every mapping ``forbidden``, or an
    ``unchanged_species`` move whose template RMG cannot determine)."""

    family: str
    direction: str
    outcome: Tuple
    statuses: Tuple[Tuple[str, int], ...]
    rules: Tuple[Tuple[str, str], ...]
    disposition: str
    reason: str
    representative: object = field(repr=False, compare=False)


@dataclass(frozen=True)
class ChannelSet:
    family: str
    direction: str
    resonance: str
    reactants: Tuple = field(repr=False, compare=False)
    channels: Tuple[Channel, ...]
    excluded: Tuple[ExcludedOutcome, ...]
    status_counts: Tuple[Tuple[str, int], ...]
    moves: Tuple = field(repr=False, compare=False)

    def by_outcome(self) -> Dict[Tuple, Tuple[Channel, ...]]:
        out = defaultdict(list)
        for ch in self.channels:
            for m in ch.members:
                out[m].append(ch)
        return {k: tuple(v) for k, v in out.items()}

    def find(self, pathway=None, products=None) -> Tuple[Channel, ...]:
        return tuple(ch for ch in self.channels
                     if (pathway is None or ch.pathway == tuple(pathway))
                     and (products is None or ch.products == tuple(sorted(products))))


def build_channels(family, reactants: Sequence, direction: str = "forward", *,
                   resonance: str = "all", select: Optional[Callable] = None,
                   keys: Optional[Callable] = None,
                   species: Optional[SpeciesKeys] = None,
                   dispositions: Optional[Dict] = None) -> ChannelSet:
    """Every channel of ``family`` on ``reactants`` (RMG Molecules with atom
    ids, as for ``rmg_moves.generate_moves``)."""
    reactants = tuple(reactants)
    moves = rm.generate_moves(family, reactants, direction, resonance=resonance, select=select)
    return channels_from_moves(family.label, direction, reactants, moves, resonance=resonance,
                               keys=keys, species=species, dispositions=dispositions)


def channels_from_moves(family_label, direction, reactants, moves, *, resonance="all",
                        keys=None, species=None, dispositions=None) -> ChannelSet:
    keys = keys or rm.product_key
    species = species or SpeciesKeys()
    dispositions = FORBIDDEN_DISPOSITIONS if dispositions is None else dispositions
    reactant_keys = tuple(species(m) for m in reactants)
    identical = len(reactants) == 2 and reactant_keys[0] == reactant_keys[1]
    reactant_spin = any(not spin_supported(m) for m in reactants)
    by_outcome = defaultdict(list)
    for m in moves:
        if m.products is not None and m.status in ("kept", "forbidden", "unchanged_species"):
            by_outcome[keys(m)].append(m)
    product_cache = {}

    def product_species(m):
        parts = rm.split_rows(m.product_rows())
        out = []
        spin = False
        for p in parts:
            sig = rm._signature(p)
            if sig not in product_cache:
                mol = rm.molecule_from_rows(p)
                product_cache[sig] = (species(mol), not spin_supported(mol))
            key, s = product_cache[sig]
            out.append(key)
            spin = spin or s
        return tuple(sorted(out)), spin

    groups = defaultdict(lambda: defaultdict(list))  # channel key -> outcome -> moves
    meta = {}
    excluded = []
    for outcome in sorted(by_outcome):
        ms = sorted(by_outcome[outcome], key=rm.Move.sort_key)
        allowed = [m for m in ms if m.status in ALLOWED_STATUSES and m.template is not None]
        if not allowed:
            excluded.append(_exclude(family_label, direction, outcome, ms, dispositions))
            continue
        prods, prod_spin = product_species(allowed[0])
        n_forbidden = sum(1 for m in ms if m.status == "forbidden")
        for m in allowed:
            kind = "kept" if m.status == "kept" else "synthetic:unchanged_species"
            ckey = (family_label, direction, tuple(m.template), tuple(sorted(reactant_keys)), prods)
            previous = meta.setdefault(ckey, (kind, prod_spin, set()))
            if previous[0] != kind:
                if prods != tuple(sorted(reactant_keys)):
                    raise ChannelError(f"channel {ckey} mixes {previous[0]} and {kind} outcomes")
                # the products ARE the reactant species: RMG's strict identity test
                # reads the mapping's resonance forms, so one role swap is
                # ``unchanged_species`` on some forms and ``kept`` on others;
                # species identity decides the channel: synthetic
                previous = (KINDS[1], previous[1], previous[2])
                meta[ckey] = previous
            groups[ckey][outcome].append(m)
            previous[2].add((outcome, n_forbidden))
    pathways_of = defaultdict(set)
    for ckey in groups:
        for o in groups[ckey]:
            pathways_of[o].add(ckey[2])
    channels = []
    for ckey in sorted(groups):
        family_l, d, pathway, reacts, prods = ckey
        kind, prod_spin, _ = meta[ckey]
        outcomes = sorted(groups[ckey])
        forb = dict(meta[ckey][2])
        others = tuple(sorted({p for o in outcomes for p in pathways_of[o]} - {pathway}))
        if reactant_spin or prod_spin:
            support = SPIN_UNSUPPORTED
        elif others:
            support = PATHWAY_AMBIGUOUS
        else:
            support = SUPPORTED
        channels.append(Channel(
            family_l, d, pathway, reacts, prods, kind, identical,
            tuple(outcomes), tuple(len(groups[ckey][o]) for o in outcomes),
            tuple(forb[o] for o in outcomes),
            tuple(groups[ckey][o][0] for o in outcomes),
            support, others))
    counts = rm.status_counts(moves)
    return ChannelSet(family_label, direction, resonance, reactants, tuple(channels),
                      tuple(excluded), tuple(sorted(counts.items())), tuple(moves))


def _exclude(family_label, direction, outcome, ms, dispositions):
    statuses = tuple(sorted(Counter(m.status for m in ms).items()))
    rules = sorted({r for m in ms if m.status == "forbidden" for r in fired_rules(m)})
    if any(m.status == "unchanged_species" for m in ms):
        return ExcludedOutcome(family_label, direction, outcome, statuses, tuple(rules),
                               "unsupported", "unchanged_species move without a template",
                               ms[0])
    found = [dispositions.get((family_label, name)) for _w, name in rules]
    if rules and all(d is not None and d.disposition == "exclude" for d in found):
        why = "; ".join(sorted({f"{d.rule}: {d.reason}" for d in found}))
        return ExcludedOutcome(family_label, direction, outcome, statuses, tuple(rules),
                               "exclude", why, ms[0])
    if any(d is not None and d.disposition == "include" for d in found):
        return ExcludedOutcome(family_label, direction, outcome, statuses, tuple(rules),
                               "unsupported", "an include disposition needs the forbidden "
                               "mapping's template, which RMG does not compute", ms[0])
    return ExcludedOutcome(family_label, direction, outcome, statuses, tuple(rules),
                           "undecided", "no disposition recorded for the fired rule(s)", ms[0])


# ---------------------------------------------------------------------------
# whole-channel normalization
# ---------------------------------------------------------------------------
def _ssa(channel, ssa_multiplier):
    return channel.ssa_multiplier if ssa_multiplier is None else ssa_multiplier


def _check_k(k_record):
    k = float(k_record)
    if not math.isfinite(k) or k < 0:
        raise ChannelError(f"k_record must be finite and non-negative, got {k_record!r}")


def member_weights(channel: Channel, k_record, ssa_multiplier=None, *,
                   exact: bool = False) -> Dict[Tuple, object]:
    """Weight of every member: ``ssa_multiplier * k_record / T_ch`` (the whole
    channel is the denominator).  ``exact=True`` returns ``Fraction`` weights,
    whose sum is exactly ``ssa_multiplier * k_record``."""
    from fractions import Fraction
    _check_k(k_record)
    if channel.size < 1:
        raise ChannelError("a channel without members has no weight")
    ssa = _ssa(channel, ssa_multiplier)
    if exact:
        w = Fraction(ssa) * Fraction(k_record) / channel.size
    else:
        w = float(ssa) * float(k_record) / channel.size
    return {m: w for m in channel.members}


def transition_weight(channel: Channel, k_record, ssa_multiplier=None) -> float:
    """Per-transition weight ``ssa_multiplier * k_record / T_ch``."""
    return next(iter(member_weights(channel, k_record, ssa_multiplier).values()))


def channel_rate_sum(channel: Channel, k_record, ssa_multiplier=None, *, exact: bool = False):
    """Sum of the member weights (exact ``Fraction`` sum, or ``math.fsum``)."""
    weights = member_weights(channel, k_record, ssa_multiplier, exact=exact)
    return sum(weights.values()) if exact else math.fsum(weights.values())


# ---------------------------------------------------------------------------
# RMG reaction of a channel (template orientation)
# ---------------------------------------------------------------------------
def _labelled_reactant_forms(channel_set, move):
    """The reactant molecules (resonance forms of the move) with its labels."""
    label_of = {a: lab for _s, lab, a in move.labels}
    out = []
    for k, mol in enumerate(channel_set.reactants):
        form = rm.reactant_forms(mol, channel_set.resonance)[move.forms[k]].copy(deep=True)
        for atom, original in zip(form.atoms, rm.reactant_forms(mol, channel_set.resonance)
                                  [move.forms[k]].atoms):
            atom.id = original.id
        form.clear_labeled_atoms()
        for atom in form.atoms:
            if atom.id in label_of:
                atom.label = label_of[atom.id]
        out.append(form)
    return out


def _labelled_products(move):
    label_of = {a: lab for lab, a in (move.product_labels or ())}
    out = []
    for part in rm.split_rows(move.product_rows()):
        mol = rm.molecule_from_rows(part)
        for atom in mol.atoms:
            if atom.id in label_of:
                atom.label = label_of[atom.id]
        out.append(mol)
    return out


def template_reaction(family, channel_set, move):
    """An RMG ``TemplateReaction`` of the move, oriented as the family template
    (forward), with labelled molecules, the move's template and Species."""
    from rmgpy.data.kinetics.family import TemplateReaction
    from rmgpy.species import Species
    reacts = _labelled_reactant_forms(channel_set, move)
    prods = _labelled_products(move)
    forward = move.direction == "forward"
    if not forward:
        reacts, prods = prods, reacts
    rxn = TemplateReaction(reactants=[Species(molecule=[m]) for m in reacts],
                           products=[Species(molecule=[m]) for m in prods],
                           degeneracy=1, reversible=family.reversible, family=family.label,
                           is_forward=True, electrons=family.electrons,
                           template=list(move.template) if move.template else None)
    return rxn, reacts, prods


@dataclass(frozen=True)
class ChannelKinetics:
    kinetics: object = field(repr=False)
    source: str
    entry: Optional[str]
    degeneracy: float
    provenance: str
    template_orientation_forward: bool

    def rate(self, temperature: float, dHrxn: float = 0.0) -> float:
        """k(T) of the RMG kinetics object (Evans-Polanyi / Blowers-Masel
        models need the reaction enthalpy; 0 for an unchanged-species move)."""
        kin = self.kinetics
        try:
            return float(kin.get_rate_coefficient(temperature, dHrxn))
        except TypeError:
            return float(kin.get_rate_coefficient(temperature))


def template_direction_degeneracy(family, channel_set: ChannelSet, channel: Channel,
                                  species: Optional[SpeciesKeys] = None) -> float:
    """RMG's path degeneracy of the channel's reaction in the family TEMPLATE
    direction (what ``get_kinetics`` multiplies a rule by): the channel's own
    convention for a forward channel; for a reverse channel, that of the
    forward channel rebuilt on the move's products (RMG's forward-direction
    recompute for reactions found backwards)."""
    if channel.direction == "forward":
        return channel.degeneracy_convention
    move = channel.representatives[0]
    products = [rm.molecule_from_rows(p) for p in rm.split_rows(move.product_rows())]
    species = species or SpeciesKeys()
    forward = build_channels(family, products, "forward", resonance=channel_set.resonance,
                             species=species)
    hits = [ch for ch in forward.channels if ch.pathway == channel.pathway
            and ch.products == channel.reactants]
    if len(hits) != 1:
        raise ChannelError(f"reverse channel {channel.key}: {len(hits)} forward channels")
    return hits[0].degeneracy_convention


def channel_kinetics(family, channel_set: ChannelSet, channel: Channel) -> ChannelKinetics:
    """RMG's own family kinetics for the channel's template, in the family
    template direction, by the call the compiler makes for a kept reaction
    (``KineticsFamily.get_kinetics(..., return_all_kinetics=False)``: training
    depository first, then rate rules / tree node), with RMG's degeneracy in
    that direction (``template_direction_degeneracy``).  A reverse channel's
    rate is this divided by Kc (not computed here)."""
    move = channel.representatives[0]
    rxn, _r, _p = template_reaction(family, channel_set, move)
    degeneracy = template_direction_degeneracy(family, channel_set, channel)
    kinetics, source, entry, is_forward = family.get_kinetics(
        rxn, template_labels=list(channel.pathway), degeneracy=degeneracy,
        return_all_kinetics=False)
    if kinetics is None:
        raise ChannelError(f"RMG returned no kinetics for {channel.key}")
    provenance = ("synthetic:unchanged_species" if channel.kind == "synthetic:unchanged_species"
                  else "rmg:family")
    label = getattr(source, "label", source)
    return ChannelKinetics(kinetics, str(label), getattr(entry, "label", None) if entry else None,
                           degeneracy, provenance, bool(is_forward))


