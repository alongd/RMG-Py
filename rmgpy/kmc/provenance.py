def _persist_generated_kinetics(kinetics):
    """Apply the same finite representation used when rules.py is saved."""
    context = KineticsDatabase().local_context
    return eval(repr(kinetics), {"__builtins__": {}}, context)


def _fit_autogenerated_node(family, node_label, reactions):
    """Fit one autogenerated node by RMG's tree-generation code path."""
    kinetics = _make_rule(
        (
            family.forward_recipe.actions,
            reactions,
            1000.0,
            1.0e5,
            node_label,
            [reaction.rank for reaction in reactions],
        )
    )
    if kinetics is None:
        raise ValueError("RMG could not fit the listed training reactions")
    return _persist_generated_kinetics(kinetics)


def run_autogenerated_oracle_positive_control(
    database_path: str | Path,
) -> dict[str, Any]:
    """Regenerate, persist, reload, and independently refit one small family."""
    database_path = Path(database_path).resolve()
    family_source = database_path / "input/kinetics/families" / ORACLE_CONTROL_FAMILY
    scratch_parent = (
        Path(__file__).resolve().parents[1] / "output/kmc-provenance/oracle-control"
    )
    scratch_parent.mkdir(parents=True, exist_ok=True)

    thermo_owner = RMGDatabase()
    thermo_owner.load_thermo(
        str(database_path / "input/thermo"),
        thermo_libraries=["primaryThermoLibrary"],
        depository=True,
    )

    def run_in_scratch(scratch: Path):
        def load_scratch_family():
            kinetics_database = KineticsDatabase()
            family = KineticsFamily(label=ORACLE_CONTROL_FAMILY)
            family.load(
                str(scratch),
                kinetics_database.local_context,
                kinetics_database.global_context,
                depository_labels=["training"],
            )
            return family

        generated = load_scratch_family()
        generated.clean_tree()
        generated.make_tree(thermo_database=thermo_owner.thermo, T=1000.0)
        generated.save(str(scratch))

        reloaded = load_scratch_family()
        training_map = _autogenerated_training_map(reloaded, thermo_owner.thermo, {})
        node_results = []
        for node_label, pairs in sorted(training_map.items()):
            stored_entries = reloaded.rules.entries.get(node_label, [])
            if not stored_entries or not pairs:
                continue
            reactions = [reaction for _, reaction in pairs]
            refit = _fit_autogenerated_node(reloaded, node_label, reactions)
            stored = stored_entries[0].data
            errors = [
                abs(
                    refit.get_rate_coefficient(temperature)
                    - stored.get_rate_coefficient(temperature)
                )
                / abs(stored.get_rate_coefficient(temperature))
                for temperature in DEFAULT_T_GRID
            ]
            node_results.append(
                {
                    "node": node_label,
                    "training_reaction_count": len(reactions),
                    "maximum_relative_error": max(errors),
                }
            )
        if not node_results:
            raise ValueError("positive-control regeneration produced no fitted nodes")
        maximum_error = max(item["maximum_relative_error"] for item in node_results)
        result = {
            "family": ORACLE_CONTROL_FAMILY,
            "source_node_count": len(node_results),
            "maximum_relative_error": maximum_error,
            "rate_matches": maximum_error <= RATE_REPRODUCTION_RTOL,
            "nodes": node_results,
        }
        if not result["rate_matches"]:
            raise ValueError(
                "fresh autogenerated rules do not reproduce after persistence: "
                f"maximum relative error {maximum_error:.12g}"
            )
        return result

    with tempfile.TemporaryDirectory(
        prefix=f"{ORACLE_CONTROL_FAMILY}-", dir=scratch_parent
    ) as scratch_name:
        scratch = Path(scratch_name)
        shutil.copytree(family_source, scratch, dirs_exist_ok=True)
        return run_in_scratch(scratch)


def _extract_git_tree(repository: Path, commit: str, prefix: str, destination: Path):
    """Extract one historical tree using only ``git show commit:path``."""
    paths = subprocess.check_output(
        ["git", "-C", str(repository), "ls-tree", "-r", "--name-only", commit, prefix],
        text=True,
    ).splitlines()
    if not paths:
        raise ValueError(f"no paths found at {commit}:{prefix}")
    for relative in paths:
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(
            subprocess.check_output(
                ["git", "-C", str(repository), "show", f"{commit}:{relative}"]
            )
        )


def _load_historical_thermo(path: Path):
    """Load the thermo inputs used by the historical generateTree script."""
    thermo = ThermoDatabase()
    thermo.depository = {}
    thermo.load_libraries(
        str(path / "libraries"), list(LEGACY_TREE_THERMO_LIBRARIES)
    )
    thermo.groups = {
        source.stem: ThermoGroups(label=source.stem).load(
            str(source), thermo.local_context, thermo.global_context
        )
        for source in sorted((path / "groups").glob("*.py"))
    }
    thermo.record_ring_generic_nodes()
    thermo.record_polycylic_generic_nodes()
    return thermo


