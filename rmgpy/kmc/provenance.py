def _legacy_bm_fit(reactions, recipe):
    """Reproduce ArrheniusBM.fit_to_reactions before the N=1 switch."""
    w0_values = get_w0s(recipe, reactions)
    w0 = sum(w0_values) / len(w0_values)
    units = ("", "s^-1", "m^3/(mol*s)", "m^6/(mol^2*s)")
    order = len(reactions[0].reactants)
    if len(reactions) == 1:
        reaction = reactions[0]
        delta_h = reaction.get_enthalpy_of_reaction(1000.0)
        activation_energy = reaction.kinetics.Ea.value_si

        def residual(E0):
            potential = 2 * w0 * (2 * w0 + 2 * E0) / (2 * w0 - 2 * E0)
            return activation_energy - (w0 + delta_h / 2.0) * (
                potential - 2 * w0 + delta_h
            ) ** 2 / (potential**2 - (2 * w0) ** 2 + delta_h**2)

        if abs(delta_h) > 4 * w0 / 10.0:
            E0 = w0 / 10.0
        else:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore", RuntimeWarning)
                E0 = fsolve(residual, w0 / 10.0)[0]
        fitted = ArrheniusBM(
            A=(reaction.kinetics.A.value_si, units[order]),
            n=reaction.kinetics.n.value_si,
            w0=(w0, "J/mol"),
            E0=(E0, "J/mol"),
            Tmin=reaction.kinetics.Tmin,
            Tmax=reaction.kinetics.Tmax,
        )
        return _persist_generated_kinetics(fitted)

    def model(inputs, lnA, n, E0):
        temperatures = inputs[:, 0]
        delta_h = inputs[:, 1]
        potential = 2 * w0 * (2 * w0 + 2 * E0) / (2 * w0 - 2 * E0)
        activation_energy = (w0 + delta_h / 2.0) * (
            potential - 2 * w0 + delta_h
        ) ** 2 / (potential**2 - (2 * w0) ** 2 + delta_h**2)
        activation_energy = np.where(delta_h < -4.0 * E0, 0.0, activation_energy)
        activation_energy = np.where(
            delta_h > 4.0 * E0, delta_h, activation_energy
        )
        return lnA + np.log(
            temperatures**n * np.exp(-activation_energy / (8.314 * temperatures))
        )

    inputs = []
    outputs = []
    sigmas = []
    for reaction in reactions:
        sigma = rank_accuracy_map[reaction.rank].value_si / 2.0
        for temperature in LEGACY_TEMPERATURE_GRID:
            inputs.append(
                [temperature, reaction.get_enthalpy_of_reaction(temperature)]
            )
            outputs.append(np.log(reaction.get_rate_coefficient(temperature)))
            sigmas.append(sigma / (8.314 * temperature))
    tolerance = 1.0e-8
    while True:
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore", OptimizeWarning)
                parameters = curve_fit(
                    model,
                    np.array(inputs),
                    np.array(outputs),
                    sigma=sigmas,
                    p0=[1.0, 1.0, w0 / 10.0],
                    xtol=tolerance,
                    ftol=tolerance,
                )[0]
            break
        except RuntimeError:
            if tolerance >= 1.0:
                raise ValueError("legacy BM fit did not converge")
            tolerance *= 10.0
    fitted = ArrheniusBM(
        A=(np.exp(parameters[0]), units[order]),
        n=parameters[1],
        w0=(w0, "J/mol"),
        E0=(parameters[2], "J/mol"),
        Tmin=(min(LEGACY_TEMPERATURE_GRID), "K"),
        Tmax=(max(LEGACY_TEMPERATURE_GRID), "K"),
    )
    return _persist_generated_kinetics(fitted)


def _kinetics_reproduction(fitted, stored):
    fitted_rates = [
        fitted.get_rate_coefficient(temperature) for temperature in DEFAULT_T_GRID
    ]
    stored_rates = [
        stored.get_rate_coefficient(temperature) for temperature in DEFAULT_T_GRID
    ]
    errors = [
        abs(actual - expected) / abs(expected)
        for actual, expected in zip(fitted_rates, stored_rates)
    ]
    maximum_error = max(errors)
    return {
        "stored_rate": {"T": list(DEFAULT_T_GRID), "k": stored_rates},
        "refit_rate": {"T": list(DEFAULT_T_GRID), "k": fitted_rates},
        "maximum_relative_error": maximum_error,
        "rate_matches": maximum_error <= RATE_REPRODUCTION_RTOL,
    }


def run_legacy_rate_oracle(
    database_path: str | Path, live_thermo_database=None
) -> dict[str, Any]:
    """Numerically reproduce the six legacy autogenerated source nodes."""
    database_path = Path(database_path).resolve()
    if live_thermo_database is None:
        live_thermo_database = ThermoDatabase()
        live_thermo_database.load(
            str(database_path / "input/thermo"),
            libraries=["primaryThermoLibrary"],
            depository=True,
        )
    scratch_parent = (
        Path(__file__).resolve().parents[1] / "output/kmc-provenance/legacy-oracle"
    )
    scratch_parent.mkdir(parents=True, exist_ok=True)
    results = []
    control = None
    with tempfile.TemporaryDirectory(prefix="historical-", dir=scratch_parent) as name:
        scratch = Path(name)
        for commit in sorted({spec[0] for spec in LEGACY_NODE_SPECS}):
            _extract_git_tree(database_path, commit, "input/thermo", scratch / commit)
            families = sorted(
                {spec[1] for spec in LEGACY_NODE_SPECS if spec[0] == commit}
            )
            for family_label in families:
                _extract_git_tree(
                    database_path,
                    commit,
                    f"input/kinetics/families/{family_label}",
                    scratch / commit,
                )

        for commit in sorted({spec[0] for spec in LEGACY_NODE_SPECS}):
            base = scratch / commit
            historical_thermo = _load_historical_thermo(base / "input/thermo")
            for family_label in sorted(
                {spec[1] for spec in LEGACY_NODE_SPECS if spec[0] == commit}
            ):
                family_path = base / "input/kinetics/families" / family_label
                family = _load_scratch_family(family_path, family_label)
                mapping = _autogenerated_training_map(
                    family, historical_thermo, {}
                )
                live_mapping = None
                for _, _, node_label in (
                    spec
                    for spec in LEGACY_NODE_SPECS
                    if spec[0] == commit and spec[1] == family_label
                ):
                    pairs = mapping[node_label]
                    reactions = [reaction for _, reaction in pairs]
                    stored = family.rules.entries[node_label][0].data
                    reproduction = _kinetics_reproduction(
                        _legacy_bm_fit(reactions, family.forward_recipe.actions),
                        stored,
                    )
                    contributors = [
                        serialize_entry(
                            entry, "training reaction", family_label
                        )
                        for entry, _ in pairs
                    ]
                    result = {
                        "family": family_label,
                        "node": node_label,
                        "historical_commit": commit,
                        "resolution": f"RESOLVED:historical-{commit[:10]}",
                        "training_reaction_count": len(reactions),
                        "contributors": contributors,
                        "contains_5002_or_5003": any(
                            item["index"] in {5002, 5003} for item in contributors
                        ),
                        **reproduction,
                    }
                    if family_label == "Disproportionation" and len(reactions) == 8:
                        live_family = _load_scratch_family(family_path, family_label)
                        live_mapping = _autogenerated_training_map(
                            live_family, live_thermo_database, {}
                        )
                        live_reactions = [
                            reaction for _, reaction in live_mapping[node_label]
                        ]
                        live_fit = _legacy_bm_fit(
                            live_reactions, live_family.forward_recipe.actions
                        )
                        result["historical_training_live_thermo_relative_error"] = (
                            _kinetics_reproduction(live_fit, stored)[
                                "maximum_relative_error"
                            ]
                        )
                        result["change_that_reproduces"] = (
                            "historical thermo files and generateTree thermo-library "
                            "order; the contributor set is unchanged"
                        )
                    elif len(reactions) == 1:
                        result["change_that_reproduces"] = (
                            "pre-d012688769 ArrheniusBM.fit_to_reactions N=1 path"
                        )
                    else:
                        result["change_that_reproduces"] = (
                            "historical N=5 training set"
                        )
                    results.append(result)

                    if family_label == "R_Recombination" and len(reactions) == 5:
                        original_A = reactions[0].kinetics.A.value_si
                        reactions[0].kinetics.A.value_si = original_A * 2.0
                        try:
                            perturbed = _kinetics_reproduction(
                                _legacy_bm_fit(
                                    reactions, family.forward_recipe.actions
                                ),
                                stored,
                            )
                        finally:
                            reactions[0].kinetics.A.value_si = original_A
                        control = {
                            "family": family_label,
                            "node": node_label,
                            "contributor": contributors[0],
                            "factor": 2.0,
                            **perturbed,
                        }
    if control is None:
        raise ValueError("legacy oracle did not execute its perturbation control")
    return {
        "single_reaction_switch_commit": LEGACY_SINGLE_REACTION_SWITCH_COMMIT,
        "fit_function": "legacy ArrheniusBM.fit_to_reactions",
        "temperature_grid_K": list(LEGACY_TEMPERATURE_GRID),
        "thermo_libraries": list(LEGACY_TREE_THERMO_LIBRARIES),
        "extraction_method": "git show <commit>:<path>",
        "source_node_count": len(results),
        "rate_matches": all(item["rate_matches"] for item in results),
        "nodes": sorted(results, key=lambda item: (item["family"], item["node"])),
        "perturbation_control": control,
    }


