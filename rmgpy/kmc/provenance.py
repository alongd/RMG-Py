def _text_values(value: Any):
    if value is None:
        return
    if isinstance(value, dict):
        for item in value.values():
            yield from _text_values(item)
    elif isinstance(value, (list, tuple)):
        for item in value:
            yield from _text_values(item)
    else:
        yield str(value)


def entry_flag_terms(entry) -> list[str]:
    """Return fixed-list terms found in an entry's descriptions or reference."""
    fields = [
        getattr(entry, "short_desc", ""),
        getattr(entry, "long_desc", ""),
    ]
    reference = getattr(entry, "reference", None)
    if reference is not None:
        fields.append(vars(reference) if hasattr(reference, "__dict__") else reference)
    haystack = "\n".join(_text_values(fields)).casefold()
    return [term for term in FLAG_TERMS if term.casefold() in haystack]


def _json_value(value: Any) -> Any:
    if value is None or isinstance(value, (bool, int, float, str)):
        return value
    if isinstance(value, (list, tuple)):
        return [_json_value(item) for item in value]
    if isinstance(value, dict):
        return {str(key): _json_value(item) for key, item in value.items()}
    return str(value)


def serialize_entry(
    entry, source_kind: str, family: str, *, weight: float | None = None
) -> dict[str, Any]:
    """Serialize the source metadata RMG loaded for one database entry."""
    reference = getattr(entry, "reference", None)
    reference_data = None
    if reference is not None:
        reference_data = {"type": type(reference).__name__}
        if hasattr(reference, "__dict__"):
            reference_data.update(
                {
                    key: _json_value(value)
                    for key, value in vars(reference).items()
                    if not key.startswith("_")
                }
            )
        else:
            reference_data["value"] = str(reference)
    terms = entry_flag_terms(entry)
    return {
        "family": family,
        "source_kind": source_kind,
        "index": getattr(entry, "index", None),
        "label": getattr(entry, "label", ""),
        "rank": getattr(entry, "rank", None),
        "weight": None if weight is None else float(weight),
        "short_desc": getattr(entry, "short_desc", ""),
        "long_desc": getattr(entry, "long_desc", ""),
        "reference_type": getattr(entry, "reference_type", ""),
        "reference": reference_data,
        "flag_terms": terms,
        "flagged": bool(terms),
    }


def canonical_json_bytes(value: Any) -> bytes:
    return json.dumps(
        value, sort_keys=True, separators=(",", ":"), ensure_ascii=True
    ).encode("utf-8")


def write_content_addressed_audit(
    audit: dict[str, Any], output_directory: str | Path
) -> Path:
    payload = canonical_json_bytes(audit)
    digest = hashlib.sha256(payload).hexdigest()
    path = Path(output_directory) / f"{digest}.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(payload)
    return path


